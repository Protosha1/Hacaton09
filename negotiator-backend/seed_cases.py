# ---------- Build and save ----------

def build_scenario(case_id, category, name, user_task, non_standard):
    defaults = CATEGORY_DEFAULTS[category]
    return Scenario(
        id=case_id,
        category=category,          # ← ДОБАВЬТЕ ЭТУ СТРОКУ
        name=name,
        description=user_task,
        user_role=defaults["user_role"],
        user_goal=user_task,
        opponent_role=defaults["opponent_role"],
        opponent_character=defaults["opponent_character"],
        opponent_goal=non_standard,
        opponent_interests=defaults["opponent_interests"],
        opponent_constraints=defaults["opponent_constraints"],
        opponent_red_lines=defaults["opponent_red_lines"],
        concession_limits=defaults["concession_limits"],
        tactics=defaults["tactics"],
        communication_style=defaults["communication_style"],
        initial_message=defaults["initial_message"],
    )


async def seed_cases():
    async with AsyncSessionLocal() as db:
        created = 0
        skipped = 0
        for case_id, category, name, user_task, non_standard in CASES:
            existing = await db.get(Scenario, case_id)
            if existing is not None:
                skipped += 1
                continue
            db.add(build_scenario(case_id, category, name, user_task, non_standard))
            created += 1
        await db.commit()

        print(f"[OK] Created: {created}")
        print(f"[INFO] Skipped (already exist): {skipped}")
        print(f"[INFO] Total cases in file: {len(CASES)}")
        print("")
        print("Categories:")
        from collections import Counter
        for cat, count in Counter(c[1] for c in CASES).items():
            print(f"  {cat}: {count}")


if __name__ == "__main__":
    asyncio.run(seed_cases())